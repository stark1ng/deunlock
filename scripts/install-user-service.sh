#!/usr/bin/env bash
# Install deunlock as a per-user systemd service — no sudo required.
#
# Puts the daemon and the CLI under ~/.local, keeps all state under
# ~/.local/share/deunlock (mode 0700), and starts deunlock-presenced.service in
# the user manager so a crashed daemon comes back on its own.
#
# The PAM side is a separate, privileged step: scripts/install-pam-system.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIBEXEC="${HOME}/.local/libexec/deunlock"
BINDIR="${HOME}/.local/bin"
STATE="${HOME}/.local/share/deunlock"
UNIT_DIR="${HOME}/.config/systemd/user"

say() { printf '  %s\n' "$*"; }

printf 'Building release binaries\n'
cargo build --release -p deunlock-presenced -p deunlock-cli -p deunlock-pam --manifest-path "${ROOT}/Cargo.toml"

printf 'Installing\n'
mkdir -p "${LIBEXEC}" "${BINDIR}" "${STATE}/keys" "${UNIT_DIR}"
chmod 0700 "${STATE}" "${STATE}/keys"
install -m 0755 "${ROOT}/target/release/deunlock-presenced" "${LIBEXEC}/deunlock-presenced"
install -m 0755 "${ROOT}/target/release/deunlock" "${LIBEXEC}/deunlock"
ln -sfn "${LIBEXEC}/deunlock" "${BINDIR}/deunlock"
say "binaries      ${LIBEXEC}"
say "state         ${STATE}"
say "symlink       ${BINDIR}/deunlock"

cat >"${UNIT_DIR}/deunlock-presenced.service" <<EOF
# Generated by deunlock/scripts/install-user-service.sh
[Unit]
Description=deunlock phone-as-key presence daemon
Documentation=https://github.com/stark1ng/deunlock
ConditionPathIsDirectory=%t
StartLimitIntervalSec=0

[Service]
Type=simple
Environment=DEUNLOCK_HOST_KEY=${STATE}/host.key
# No /etc/deunlock on a per-user install: the daemon mints this identity on
# first start. Losing it means re-pairing, so back it up with the bonds.
ExecStart=${LIBEXEC}/deunlock-presenced \\
    --socket %t/deunlock/auth.sock \\
    --bonds-file ${STATE}/bonds.toml \\
    --keys-dir ${STATE}/keys \\
    --audit-log ${STATE}/last.log \\
    --pidfile %t/deunlock/presenced.pid \\
    --log-level info
KillSignal=SIGTERM
TimeoutStopSec=5
# A dead Bluetooth health-probe used to leave the daemon gone until a human
# noticed. Come back, always.
Restart=on-failure
RestartSec=2
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=${STATE} %t

[Install]
WantedBy=default.target
EOF
say "unit          ${UNIT_DIR}/deunlock-presenced.service"

systemctl --user daemon-reload
systemctl --user enable deunlock-presenced.service
# `enable --now` is a no-op on an already-running unit, which would leave the
# previous binary in memory after an upgrade.
systemctl --user restart deunlock-presenced.service

printf 'Waiting for the socket\n'
for _ in $(seq 1 25); do
    if [ -S "${XDG_RUNTIME_DIR}/deunlock/auth.sock" ]; then
        say "socket        ${XDG_RUNTIME_DIR}/deunlock/auth.sock"
        break
    fi
    sleep 0.2
done

systemctl --user --no-pager --lines=6 status deunlock-presenced.service || true
printf '\nNext: bash %s/scripts/install-pam-system.sh (asks for your password once)\n' "${ROOT}"
